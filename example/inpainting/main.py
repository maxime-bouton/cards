def main(mode, config_file_name):
    config_file = open(config_file_name)
    params = json.load(config_file)

    args = {
        "nb_batches": params["nbCheckpoint"],
        "batch_size": params["sampleSize"],
        "save_path": params["savePath"],
        "split_coef": params["alpha"],
        "reg_coef": params["regularizationCoefficient"],
        "seed": params["seed"],
        "data_path": params["dataPath"],
    }

    args_analysis = {
        "nb_batches": params["nbCheckpoint"],
        "burnin": params["burnin"],
        "save_path": params["savePath"],
        "data_path": params["dataPath"],
    }

    if not exists(args["data_path"]):
        generate_observations(params["originPath"], params["dataPath"])

    if mode == "serial":
        pathlib.Path(params["savePath"]).mkdir(parents=True, exist_ok=True)
        compute_serial(**args)
        analyze_data(**args_analysis, output_file_name="results_inpainting_serial")

    if mode == "gpu":
        pathlib.Path(params["savePath"]).mkdir(parents=True, exist_ok=True)
        compute_gpu(**args)
        analyze_data(**args_analysis, output_file_name="results_inpainting_gpu")

    if mode == "distributed":
        from mpi4py import MPI

        if MPI.COMM_WORLD.Get_rank() == 0:
            pathlib.Path(params["savePath"]).mkdir(parents=True, exist_ok=True)

        compute_distributed(**args)

        if MPI.COMM_WORLD.Get_rank() == 0:
            analyze_data(**args_analysis, output_file_name="results_inpainting_mpi")


if __name__ == "__main__":
    # main(mode="serial", config_file_name="config.json")
    main(mode="gpu", config_file_name="config.json")
